#!/usr/bin/env bash
# Regenerates the committed bindings, src/bindings/x86_64-unknown-linux-gnu.rs, with bindgen, from wrapper.h and
# the ggml submodule. Run it after moving the ggml pin or changing wrapper.h, on x86_64 Linux, and commit the
# result. Needs libclang (LIBCLANG_PATH if it is not found, and BINDGEN_EXTRA_CLANG_ARGS=-I<gcc include dir> if
# libclang's resource headers such as stdbool.h are missing).
set -euo pipefail
here=$(cd "$(dirname "$0")/.." && pwd)
root=$(cd "$here/../.." && pwd)
target=x86_64-unknown-linux-gnu
[ "$(rustc -vV | sed -n 's/^host: //p')" = "$target" ] || { echo "run this on $target" >&2; exit 2; }

cd "$root"
cargo build --locked -p ggtts-ggml-sys --features bindgen --message-format=json-render-diagnostics > "$here/target-msgs.json"
out=$(sed -n 's/.*"package_id":"[^"]*ggtts-ggml-sys[^"]*".*"out_dir":"\([^"]*\)".*/\1/p' "$here/target-msgs.json" | tail -n 1)
rm -f "$here/target-msgs.json"
[ -n "$out" ] && [ -f "$out/bindings.rs" ] || { echo "bindgen output not found" >&2; exit 1; }
{
  echo "// Generated by bindgen from wrapper.h and ggml at $(git -C "$here/ggml" rev-parse HEAD)."
  echo "// Do not edit: run crates/ggtts-ggml-sys/scripts/regenerate-bindings.sh."
  cat "$out/bindings.rs"
} > "$here/src/bindings/$target.rs"
echo "wrote $here/src/bindings/$target.rs ($(wc -l < "$here/src/bindings/$target.rs") lines)"
