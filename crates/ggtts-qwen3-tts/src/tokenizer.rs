//! The text tokenizer: qwen3-tts.cpp's `TextTokenizer` at `16bb5af`, ported so that it gives the same token ids for
//! the same bytes.
//!
//! It is a byte-level BPE in three steps, each following a named part of the reference:
//!
//! 1. **Pre-tokenizer** ([`pre_tokenize`]): the GPT-2 split `'s|'t|'re|'ve|'m|'ll|'d| ?\p{L}+| ?\p{N}+|
//!    ?[^\s\p{L}\p{N}]+|\s+(?!\S)`, as the hand-written matcher `unicode_regex_split_custom_gpt2`
//!    (`src/tokenizer_unicode.cpp:214-330`) implements it, not as a regex engine would. Note that this is the GPT-2
//!    expression the reference selects (`src/text_tokenizer.cpp:11-13`), not Qwen2's own pre-tokenizer.
//! 2. **Byte encoding**: each piece's UTF-8 bytes mapped to GPT-2's printable characters
//!    (`unicode_byte_encoding_process`, `src/tokenizer_unicode.cpp:148-212`).
//! 3. **BPE** ([`Tokenizer::encode`]): repeated lowest-rank pair merges (`TextTokenizer::bpe` and `get_min_pair`,
//!    `src/text_tokenizer.cpp:197-262`), then a vocabulary lookup with a per-character fallback
//!    (`src/text_tokenizer.cpp:264-306`).
//!
//! There is no normalization step: the reference applies none (no NFC/NFD, no lowercasing) before splitting.
//!
//! The prompt forms the pipeline feeds the talker are plain id assembly around [`Tokenizer::encode`]:
//! [`Tokenizer::encode_for_tts`], [`Tokenizer::encode_reference_for_tts`] and [`Tokenizer::encode_instruct`]
//! (`src/text_tokenizer.cpp:308-394`, called from `src/pipeline/pipeline_synthesize.cpp:1320-1333`).
//!
//! The codepoint classes the pre-tokenizer reads come from the reference's own tables
//! (`src/tokenizer_unicode_data.cpp`, generated by llama.cpp's `gen-unicode-data.py`), reduced to the four classes
//! the GPT-2 matcher distinguishes; see [`CLASS_RUNS`]. They are that file's Unicode version, not Rust's.

use std::collections::HashMap;

use ggtts_core::engine::EngineError;

/// The codepoint classes `unicode_regex_split_custom_gpt2` tests, in the priority it tests them: `is_letter`, then
/// `is_number`, then `is_whitespace`, then "any flag set" (`as_uint() != 0`). Every codepoint below 0x110000 has
/// some flag set in the reference's tables, so [`Class::None`] only arises outside the text being split, where
/// `_get_flags` returns empty flags (`src/tokenizer_unicode.cpp:233-235`).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Class {
    /// `\p{L}`.
    Letter,
    /// `\p{N}`.
    Number,
    /// `\s` as the reference defines it (`unicode_set_whitespace`), and neither a letter nor a number.
    Whitespace,
    /// Anything else with a flag set: punctuation, symbols, marks, controls, unassigned codepoints.
    Other,
    /// No flags: past either end of the text.
    None,
}

/// The class of a codepoint, from [`CLASS_RUNS`]. Codepoints at or above 0x110000 are `UNDEFINED` in the reference
/// (`unicode_cpt_flags_from_cpt`, `src/tokenizer_unicode.cpp:846-850`), so [`Class::Other`].
pub fn class_of(cpt: u32) -> Class {
    if cpt >= 0x110000 {
        return Class::Other;
    }
    let i = CLASS_RUNS.partition_point(|&r| (r >> 2) <= cpt) - 1;
    match CLASS_RUNS[i] & 3 {
        1 => Class::Letter,
        2 => Class::Number,
        3 => Class::Whitespace,
        _ => Class::Other,
    }
}

/// `unicode_cpt_from_utf8` (`src/tokenizer_unicode.cpp:30-65`), including what it accepts that strict UTF-8 does
/// not: overlong forms and surrogates decode to their value, and a 4-byte lead of F4 90 or above yields a value past
/// 0x10FFFF. An `Err` is the reference's `invalid_argument`.
fn cpt_from_utf8(s: &[u8], offset: &mut usize) -> Result<u32, ()> {
    let o = *offset;
    let b0 = s[o] as u32;
    let cont = |i: usize| o + i < s.len() && (s[o + i] & 0xc0) == 0x80;
    if b0 & 0x80 == 0 {
        *offset += 1;
        return Ok(b0);
    }
    if b0 & 0x40 == 0 {
        return Err(());
    }
    if b0 & 0x20 == 0 {
        if !cont(1) {
            return Err(());
        }
        *offset += 2;
        return Ok(((b0 & 0x1f) << 6) | (s[o + 1] as u32 & 0x3f));
    }
    if b0 & 0x10 == 0 {
        if !cont(1) || !cont(2) {
            return Err(());
        }
        *offset += 3;
        return Ok(((b0 & 0x0f) << 12) | ((s[o + 1] as u32 & 0x3f) << 6) | (s[o + 2] as u32 & 0x3f));
    }
    if b0 & 0x08 == 0 {
        if !cont(1) || !cont(2) || !cont(3) {
            return Err(());
        }
        *offset += 4;
        return Ok(((b0 & 0x07) << 18)
            | ((s[o + 1] as u32 & 0x3f) << 12)
            | ((s[o + 2] as u32 & 0x3f) << 6)
            | (s[o + 3] as u32 & 0x3f));
    }
    Err(())
}

/// `unicode_cpts_from_utf8` (`src/tokenizer_unicode.cpp:829-844`): an undecodable byte becomes U+FFFD and decoding
/// resumes at the next byte.
pub fn cpts_from_utf8(s: &[u8]) -> Vec<u32> {
    let mut out = Vec::with_capacity(s.len());
    let mut offset = 0;
    while offset < s.len() {
        match cpt_from_utf8(s, &mut offset) {
            Ok(c) => out.push(c),
            Err(()) => {
                offset += 1;
                out.push(0xFFFD);
            }
        }
    }
    out
}

/// `unicode_cpt_to_utf8` (`src/tokenizer_unicode.cpp:787-814`), which encodes surrogates as it was given them. An
/// `Err` is its `invalid argument` throw for a value past 0x10FFFF, which the reference does not catch.
fn cpt_to_utf8(cpt: u32, out: &mut Vec<u8>) -> Result<(), EngineError> {
    if cpt <= 0x7f {
        out.push(cpt as u8);
    } else if cpt <= 0x7ff {
        out.extend([0xc0 | ((cpt >> 6) & 0x1f) as u8, 0x80 | (cpt & 0x3f) as u8]);
    } else if cpt <= 0xffff {
        out.extend([
            0xe0 | ((cpt >> 12) & 0x0f) as u8,
            0x80 | ((cpt >> 6) & 0x3f) as u8,
            0x80 | (cpt & 0x3f) as u8,
        ]);
    } else if cpt <= 0x10ffff {
        out.extend([
            0xf0 | ((cpt >> 18) & 0x07) as u8,
            0x80 | ((cpt >> 12) & 0x3f) as u8,
            0x80 | ((cpt >> 6) & 0x3f) as u8,
            0x80 | (cpt & 0x3f) as u8,
        ]);
    } else {
        return Err(EngineError(format!("invalid codepoint 0x{cpt:X}")));
    }
    Ok(())
}

/// GPT-2's byte-to-character map (`unicode_byte_to_utf8_map`, `src/tokenizer_unicode.cpp:148-170`, the same table
/// as `BYTE_TO_UNICODE`, `src/text_tokenizer.cpp:15-34`): printable Latin-1 bytes map to themselves, the other 68
/// bytes, in order, to U+0100 upwards.
fn byte_to_char(b: u8) -> char {
    let printable = |c: u32| (0x21..=0x7e).contains(&c) || (0xa1..=0xac).contains(&c) || (0xae..=0xff).contains(&c);
    let c = b as u32;
    if printable(c) {
        return char::from_u32(c).unwrap();
    }
    let n = (0..c).filter(|&x| !printable(x)).count() as u32;
    char::from_u32(256 + n).unwrap()
}

/// The GPT-2 pre-tokenizer over a whole text, as piece lengths in codepoints: `unicode_regex_split_custom_gpt2`
/// (`src/tokenizer_unicode.cpp:214-330`) with the single initial offset `unicode_regex_split` gives it
/// (`src/tokenizer_unicode.cpp:988`). The branches below are the reference's, in its order.
pub fn split_gpt2(cpts: &[u32]) -> Vec<usize> {
    const OUT_OF_RANGE: u32 = 0xFFFF_FFFF;
    let end = cpts.len();
    let get_cpt = |pos: usize| if pos < end { cpts[pos] } else { OUT_OF_RANGE };
    let get_class = |pos: usize| if pos < end { class_of(cpts[pos]) } else { Class::None };
    let is_space = |c: u32| c == ' ' as u32;

    let mut pieces = Vec::new();
    let mut prev_end = 0usize;
    let mut add = |to: usize, prev_end: &mut usize| -> usize {
        let len = to - *prev_end;
        if len > 0 {
            pieces.push(len);
        }
        *prev_end = to;
        len
    };

    let mut pos = 0usize;
    while pos < end {
        let cpt = get_cpt(pos);
        let class = get_class(pos);

        // 's|'t|'re|'ve|'m|'ll|'d (case-sensitive), lines 258-274.
        if cpt == '\'' as u32 && pos + 1 < end {
            let next = get_cpt(pos + 1);
            if [b's', b't', b'm', b'd'].iter().any(|&c| next == c as u32) {
                pos += add(pos + 2, &mut prev_end);
                continue;
            }
            if pos + 2 < end {
                let nn = get_cpt(pos + 2);
                let pair = |a: u8, b: u8| next == a as u32 && nn == b as u32;
                if pair(b'r', b'e') || pair(b'v', b'e') || pair(b'l', b'l') {
                    pos += add(pos + 3, &mut prev_end);
                    continue;
                }
            }
        }

        let mut class2 = if is_space(cpt) { get_class(pos + 1) } else { class };
        // <space>?\p{L}+, lines 277-285.
        if class2 == Class::Letter {
            pos += is_space(cpt) as usize;
            while class2 == Class::Letter {
                pos += 1;
                class2 = get_class(pos);
            }
            add(pos, &mut prev_end);
            continue;
        }
        // <space>?\p{N}+, lines 286-294.
        if class2 == Class::Number {
            pos += is_space(cpt) as usize;
            while class2 == Class::Number {
                pos += 1;
                class2 = get_class(pos);
            }
            add(pos, &mut prev_end);
            continue;
        }
        // <space>?[^\s\p{L}\p{N}]+, lines 295-303: not whitespace, letter or number, and some flag set.
        if class2 == Class::Other {
            pos += is_space(cpt) as usize;
            while class2 == Class::Other {
                pos += 1;
                class2 = get_class(pos);
            }
            add(pos, &mut prev_end);
            continue;
        }

        let mut n_ws = 0;
        while get_class(pos + n_ws) == Class::Whitespace {
            n_ws += 1;
        }
        // \s+(?!\S), lines 310-315: a whitespace run followed by more text leaves its last character to the next piece.
        if n_ws > 1 && get_cpt(pos + n_ws) != OUT_OF_RANGE {
            pos += n_ws - 1;
            add(pos, &mut prev_end);
            continue;
        }
        // \s+, lines 317-322.
        if n_ws > 0 {
            pos += n_ws;
            add(pos, &mut prev_end);
            continue;
        }
        // No match, lines 324-325.
        pos += 1;
        add(pos, &mut prev_end);
    }
    pieces
}

/// `unicode_regex_split(text, GPT2_REGEX_EXPRS)` (`src/tokenizer_unicode.cpp:915-1103`): the pieces, each already
/// byte-encoded into GPT-2 characters. Fails only where the reference throws: invalid UTF-8 that decodes past
/// 0x10FFFF.
pub fn pre_tokenize(text: &[u8]) -> Result<Vec<String>, EngineError> {
    let cpts = cpts_from_utf8(text);
    let mut words = Vec::new();
    let mut start = 0;
    for len in split_gpt2(&cpts) {
        // Lines 1093-1100 rebuild the piece's bytes from its codepoints; unicode_byte_encoding_process then decodes
        // and re-encodes them, which is the identity on what cpt_to_utf8 wrote, and byte-encodes the result.
        let mut bytes = Vec::new();
        for &c in &cpts[start..start + len] {
            cpt_to_utf8(c, &mut bytes)?;
        }
        start += len;
        words.push(bytes.iter().map(|&b| byte_to_char(b)).collect());
    }
    Ok(words)
}

/// `TextTokenizer::utf8_len` (`src/text_tokenizer.cpp:51-57`): the length of a character from its lead byte.
fn utf8_len(b: u8) -> usize {
    if b & 0x80 == 0 {
        1
    } else if b & 0xE0 == 0xC0 {
        2
    } else if b & 0xF0 == 0xE0 {
        3
    } else if b & 0xF8 == 0xF0 {
        4
    } else {
        1
    }
}

/// The characters of a byte-encoded token, split as `TextTokenizer` splits them.
fn chars_of(s: &str) -> Vec<&str> {
    let b = s.as_bytes();
    let mut out = Vec::new();
    let mut i = 0;
    while i < b.len() {
        let len = utf8_len(b[i]).min(b.len() - i);
        out.push(&s[i..i + len]);
        i += len;
    }
    out
}

/// The loaded tokenizer: `TextTokenizer` after `load_from_gguf` (`src/text_tokenizer.cpp:85-195`).
pub struct Tokenizer {
    vocab: HashMap<String, i32>,
    id_to_token: Vec<String>,
    /// Merge ranks keyed by the merge line itself, `"first second"`. A byte-encoded token never contains a space,
    /// so this is the reference's `(first, second)` key. A merge listed twice keeps its later rank, as the
    /// reference's `bpe_ranks_[{first, second}] = i` does.
    ranks: HashMap<String, i32>,
    /// `<|im_start|>`.
    pub bos_token_id: i32,
    /// `<|im_end|>`.
    pub eos_token_id: i32,
    /// `<|im_pad|>` is not looked up by the reference: `tokenizer.ggml.padding_token_id`, else 151643.
    pub pad_token_id: i32,
    pub assistant_token_id: i32,
    pub user_token_id: i32,
    pub newline_token_id: i32,
}

impl Tokenizer {
    /// Builds the tokenizer from a vocabulary and merge lines, with the reference's resolution of the special ids
    /// (`src/text_tokenizer.cpp:104-191`). `special` holds the values of the GGUF integer keys, in the order the
    /// reference reads them: `tokenizer.ggml.bos_token_id`, `tokenizer.ggml.eos_token_id`,
    /// `tokenizer.ggml.padding_token_id`, `qwen3-tts.text.im_start_id`, `qwen3-tts.text.im_end_id`; `None` where the
    /// key is absent.
    pub fn from_parts(tokens: Vec<String>, merges: &[String], special: [Option<i32>; 5]) -> Result<Self, EngineError> {
        if tokens.is_empty() {
            return Err(EngineError("Empty vocabulary".into()));
        }
        let mut vocab = HashMap::with_capacity(tokens.len());
        for (i, t) in tokens.iter().enumerate() {
            vocab.insert(t.clone(), i as i32);
        }
        let mut ranks = HashMap::with_capacity(merges.len());
        for (i, m) in merges.iter().enumerate() {
            if m.contains(' ') {
                ranks.insert(m.clone(), i as i32);
            }
        }
        // tokenizer_config's defaults (src/text_tokenizer.h:13-18), then the keys, then the vocabulary.
        let [bos, eos, pad, im_start, im_end] = special;
        let mut bos_token_id = bos.unwrap_or(151644);
        let mut eos_token_id = eos.unwrap_or(151645);
        let pad_token_id = pad.unwrap_or(151643);
        if let Some(v) = im_start {
            bos_token_id = v;
        }
        if let Some(v) = im_end {
            eos_token_id = v;
        }
        let find = |t: &str| vocab.get(t).copied().unwrap_or(-1);
        let or = |a: i32, b: &str| if a >= 0 { a } else { find(b) };
        // Not found under either spelling leaves -1, not the header's default (lines 166-175).
        let assistant_token_id = or(find("assistant"), "Ġassistant");
        let user_token_id = or(find("user"), "Ġuser");
        if let Some(&v) = vocab.get("<|im_start|>") {
            bos_token_id = v;
        }
        if let Some(&v) = vocab.get("<|im_end|>") {
            eos_token_id = v;
        }
        let newline_token_id = or(find("Ċ"), "\n");
        Ok(Self {
            vocab,
            id_to_token: tokens,
            ranks,
            bos_token_id,
            eos_token_id,
            pad_token_id,
            assistant_token_id,
            user_token_id,
            newline_token_id,
        })
    }

    /// `load_from_gguf` on an open GGUF file, normally the talker's, which carries `tokenizer.ggml.tokens` and
    /// `tokenizer.ggml.merges`.
    #[cfg(feature = "ggml")]
    pub fn load(g: &crate::gguf::Gguf) -> Result<Self, EngineError> {
        let tokens = g
            .strings("tokenizer.ggml.tokens")
            .ok_or_else(|| EngineError("tokenizer.ggml.tokens not found in GGUF".into()))?;
        let merges = g.strings("tokenizer.ggml.merges").unwrap_or_default();
        let key = |k: &str| g.has(k).then(|| g.u32_or(k, 0));
        Self::from_parts(
            tokens,
            &merges,
            [
                key("tokenizer.ggml.bos_token_id"),
                key("tokenizer.ggml.eos_token_id"),
                key("tokenizer.ggml.padding_token_id"),
                key("qwen3-tts.text.im_start_id"),
                key("qwen3-tts.text.im_end_id"),
            ],
        )
    }

    pub fn vocab_size(&self) -> usize {
        self.id_to_token.len()
    }

    fn rank(&self, a: &str, b: &str) -> Option<i32> {
        let mut key = String::with_capacity(a.len() + 1 + b.len());
        key.push_str(a);
        key.push(' ');
        key.push_str(b);
        self.ranks.get(&key).copied()
    }

    /// `TextTokenizer::bpe` with `get_min_pair` (`src/text_tokenizer.cpp:197-262`): find the lowest-ranked adjacent
    /// pair (the first such position on a tie), merge every occurrence of it left to right, repeat until no pair
    /// has a rank or one symbol is left.
    fn bpe(&self, token: &str) -> Vec<String> {
        let mut word: Vec<String> = chars_of(token).into_iter().map(str::to_owned).collect();
        if word.len() <= 1 {
            return word;
        }
        loop {
            let mut best: Option<(i32, usize)> = None;
            for i in 0..word.len() - 1 {
                if let Some(r) = self.rank(&word[i], &word[i + 1]) {
                    if best.is_none_or(|(br, _)| r < br) {
                        best = Some((r, i));
                    }
                }
            }
            let Some((_, at)) = best else { break };
            let (first, second) = (word[at].clone(), word[at + 1].clone());
            let mut merged = Vec::with_capacity(word.len());
            let mut j = 0;
            while j < word.len() {
                if j + 1 < word.len() && word[j] == first && word[j + 1] == second {
                    merged.push(format!("{first}{second}"));
                    j += 2;
                } else {
                    merged.push(std::mem::take(&mut word[j]));
                    j += 1;
                }
            }
            word = merged;
            if word.len() == 1 {
                break;
            }
        }
        word
    }

    /// `TextTokenizer::encode` (`src/text_tokenizer.cpp:264-306`) on raw bytes, invalid UTF-8 included. The three
    /// special spellings are recognised only as the whole text.
    pub fn encode_bytes(&self, text: &[u8]) -> Result<Vec<i32>, EngineError> {
        match text {
            b"<|im_start|>" => return Ok(vec![self.bos_token_id]),
            b"<|im_end|>" => return Ok(vec![self.eos_token_id]),
            b"<|im_pad|>" => return Ok(vec![self.pad_token_id]),
            _ => {}
        }
        let mut words = pre_tokenize(text)?;
        if words.is_empty() && !text.is_empty() {
            words.push(text.iter().map(|&b| byte_to_char(b)).collect());
        }
        let mut ids = Vec::new();
        for w in &words {
            for tok in self.bpe(w) {
                match self.vocab.get(&tok) {
                    Some(&id) => ids.push(id),
                    // Unknown: the token's characters one by one, skipping any not in the vocabulary.
                    None => ids.extend(chars_of(&tok).into_iter().filter_map(|c| self.vocab.get(c).copied())),
                }
            }
        }
        Ok(ids)
    }

    /// [`Tokenizer::encode_bytes`] on a string. Valid UTF-8 cannot reach the one failure, so this cannot fail.
    pub fn encode(&self, text: &str) -> Vec<i32> {
        self.encode_bytes(text.as_bytes())
            .expect("valid UTF-8 decodes within the codepoint range")
    }

    /// `<|im_start|>assistant\n{text}<|im_end|>\n<|im_start|>assistant\n`: the text prompt of a synthesis
    /// (`encode_for_tts`, `src/text_tokenizer.cpp:338-375`).
    pub fn encode_for_tts(&self, text: &[u8]) -> Result<Vec<i32>, EngineError> {
        let mut ids = self.reference_for_tts(text)?;
        ids.extend([self.bos_token_id, self.assistant_token_id, self.newline_token_id]);
        Ok(ids)
    }

    /// `<|im_start|>assistant\n{text}<|im_end|>\n`: the reference text of a voice-clone prompt
    /// (`encode_reference_for_tts`, `src/text_tokenizer.cpp:377-394`).
    pub fn encode_reference_for_tts(&self, text: &[u8]) -> Result<Vec<i32>, EngineError> {
        self.reference_for_tts(text)
    }

    fn reference_for_tts(&self, text: &[u8]) -> Result<Vec<i32>, EngineError> {
        self.wrap(self.assistant_token_id, text)
    }

    /// `<|im_start|>user\n{instruct}<|im_end|>\n`, and nothing for an empty instruction (`encode_instruct`,
    /// `src/text_tokenizer.cpp:308-336`).
    pub fn encode_instruct(&self, instruct: &[u8]) -> Result<Vec<i32>, EngineError> {
        if instruct.is_empty() {
            return Ok(Vec::new());
        }
        self.wrap(self.user_token_id, instruct)
    }

    fn wrap(&self, role: i32, text: &[u8]) -> Result<Vec<i32>, EngineError> {
        let mut ids = vec![self.bos_token_id, role, self.newline_token_id];
        ids.extend(self.encode_bytes(text)?);
        ids.extend([self.eos_token_id, self.newline_token_id]);
        Ok(ids)
    }

    /// `decode_token` (`src/text_tokenizer.cpp:404-413`): the token's bytes, with any character outside the GPT-2
    /// byte map kept as its own UTF-8; nothing for an id out of range.
    pub fn decode_token(&self, id: i32) -> Vec<u8> {
        let Some(tok) = usize::try_from(id).ok().and_then(|i| self.id_to_token.get(i)) else {
            return Vec::new();
        };
        let mut out = Vec::new();
        for ch in chars_of(tok) {
            let mut it = ch.chars();
            match (it.next(), it.next()) {
                (Some(c), None) => match (0..=255u8).find(|&b| byte_to_char(b) == c) {
                    Some(b) => out.push(b),
                    None => out.extend_from_slice(ch.as_bytes()),
                },
                _ => out.extend_from_slice(ch.as_bytes()),
            }
        }
        out
    }

    /// `decode` (`src/text_tokenizer.cpp:396-402`).
    pub fn decode(&self, ids: &[i32]) -> Vec<u8> {
        ids.iter().flat_map(|&id| self.decode_token(id)).collect()
    }
}

/// The class of every codepoint below 0x110000 as runs: each entry is `start << 2 | class`, with class 0 Other,
/// 1 Letter, 2 Number, 3 Whitespace, and a run lasting until the next entry's start. Derived from
/// `src/tokenizer_unicode_data.cpp` at `16bb5af`; `tests::class_table_matches_reference_data` re-derives it and
/// compares every codepoint.
