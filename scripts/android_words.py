#!/usr/bin/env python3
"""Generate the demo's EnglishWords (android/demo/.../Words.kt) from its English string resources.

    python3 scripts/android_words.py           # write Words.kt from res/values/strings.xml
    python3 scripts/android_words.py --check   # exit 1 if Words.kt is not what strings.xml generates

The plain-Kotlin classes of the demo (DemoController, About, EngineCosts) run in JVM tests without Android, so they
read their English through EnglishWords, a map of every string resource's English. This script is the one way that
map is written: change res/values/strings.xml, then run it. WordsTest (englishWordsIsTheEnglishResources) also holds
the map equal to the file, so a resource changed without running this fails the build's tests.
"""

import argparse
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEMO = ROOT / "android/demo/src/main"
STRINGS = DEMO / "res/values/strings.xml"
WORDS = DEMO / "kotlin/ggtts/demo/Words.kt"


def unescape(s):
    """Android resource escapes: \\' \\" \\n \\t \\\\; anything else after a backslash is itself."""
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            n = s[i + 1]
            out.append({"n": "\n", "t": "\t"}.get(n, n))
            i += 2
            continue
        out.append(c)
        i += 1
    return "".join(out)


def kotlin(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("\n", "\\n") + '"'


def generate(strings_xml):
    entries = [(e.get("name"), unescape(e.text or "")) for e in ET.fromstring(strings_xml).findall("string")]
    lines = ",\n".join(f"        {kotlin(k)} to {kotlin(v)}" for k, v in entries)
    return f'''// The demo's words, for the plain-Kotlin classes (DemoController, About, EngineCosts) that the JVM tests run without
// Android: they say what they say through [Words], by the resource name. On a phone that is [ResourceWords], the
// app's string resources in the phone's language; in a test, and by default, it is [EnglishWords], the English values.
//
// GENERATED by scripts/android_words.py from res/values/strings.xml: edit the resources and run it, never this file.
package ggtts.demo

import java.util.Locale

/** The text for a string resource name, with its format arguments. */
fun interface Words {{
    fun get(key: String, vararg args: Any?): String
}}

/**
 * The English values of `res/values/strings.xml`, the default locale's, generated from it. WordsTest also holds this
 * map equal to that file, so a resource changed without regenerating fails. Formatted with the root locale.
 */
object EnglishWords : Words {{
    val TEXT: Map<String, String> = mapOf(
{lines},
    )

    override fun get(key: String, vararg args: Any?): String {{
        val s = TEXT[key] ?: error("no English text for $key")
        return if (args.isEmpty()) s else String.format(Locale.ROOT, s, *args)
    }}

    /** The resource name whose English is [text] (an unformatted string), so a screen can show it translated. */
    fun keyOf(text: String): String? = TEXT.entries.firstOrNull {{ it.value == text }}?.key
}}
''', len(entries)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--check", action="store_true", help="exit 1 if Words.kt differs from what strings.xml generates")
    a = p.parse_args()
    src, n = generate(STRINGS.read_text(encoding="utf-8"))
    if a.check:
        if WORDS.read_text(encoding="utf-8") != src:
            print(f"{WORDS.relative_to(ROOT)} is not what {STRINGS.relative_to(ROOT)} generates: "
                  "run python3 scripts/android_words.py", file=sys.stderr)
            return 1
        print(f"android_words: Words.kt matches strings.xml ({n} strings)")
        return 0
    WORDS.write_text(src, encoding="utf-8", newline="\n")
    print(f"android_words: wrote {WORDS.relative_to(ROOT)} ({n} strings)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
